import { notFound } from "next/navigation";
import { and, eq } from "drizzle-orm";
import { requireUser } from "@/server/auth";
import { db, schema } from "@/server/db";
import { userAccounts } from "@/server/analytics";
import { selectedAccount } from "@/server/prefs";
import { aiConfigured } from "@/server/ai/client";
import { listConversations, loadConversation } from "@/server/ai/coach";
import { tradeQuestion, toolList } from "@/domain/ai/coach";
import { Card, Empty, Note, PageHeader } from "@/components/ui";
import { CoachChat } from "@/components/ai/CoachChat";
import { CoachConversations } from "@/components/ai/CoachConversations";
import { CoachMessage } from "@/components/ai/CoachMessage";
import { fmtDate } from "@/lib/format";

export const metadata = { title: "Coach" };

const one = (v: string | string[] | undefined) => (typeof v === "string" ? v : undefined);

export default async function CoachPage({ searchParams }: { searchParams: Promise<Record<string, string | string[] | undefined>> }) {
  const user = await requireUser();
  const sp = await searchParams;
  const c = one(sp.c);
  const current = c ? loadConversation(user.id, c) : null;
  if (c && !current) notFound();
  const tradeId = one(sp.trade);
  const trade = tradeId ? db.select({ seq: schema.trades.seq }).from(schema.trades).where(and(eq(schema.trades.id, tradeId), eq(schema.trades.userId, user.id))).get() : undefined;
  const accountId = await selectedAccount(user.id);
  const scope = accountId ? `account “${userAccounts(user.id).find((a) => a.id === accountId)?.name ?? ""}”` : "all accounts";
  const ready = aiConfigured();
  const conversations = listConversations(user.id).map((x) => ({ id: x.id, title: x.title, when: fmtDate(x.updatedAt, user.timezone) }));
  const messages = (current?.messages ?? []).map((m) => ({ id: m.id, role: m.role, content: m.content, tools: m.tools }));

  return (
    <>
      <PageHeader title="Coach" sub="Questions about your own trading, answered from your journal. The coach is asked to give sample sizes and tag what each claim rests on." />
      <div className="grid grid-cols-1 gap-3 lg:grid-cols-[240px_minmax(0,1fr)]">
        <div className="order-2 lg:order-1"><CoachConversations items={conversations} currentId={current?.conversation.id ?? null} /></div>
        <div className="order-1 min-w-0 lg:order-2">
          {ready ? (
            <CoachChat key={current?.conversation.id ?? "new"} conversationId={current?.conversation.id ?? null} initial={messages}
              initialLinks={current?.links ?? {}} prefill={trade ? tradeQuestion(trade.seq) : ""} scope={scope} />
          ) : (
            <div className="space-y-3">
              <Note tone="neutral">Not configured: add ANTHROPIC_API_KEY on the server to use the coach. Nothing is simulated without it; your journal, analytics and reviews work as before.</Note>
              {current ? (
                <Card title={current.conversation.title || "Conversation"}>
                  <div className="space-y-4">
                    {messages.map((m) => m.role === "user"
                      ? <p key={m.id} className="whitespace-pre-wrap rounded-md border border-line bg-surface-2 px-3 py-2 text-[13px]">{m.content}</p>
                      : <div key={m.id}><CoachMessage text={m.content} links={current.links} />{m.tools && <p className="mt-1 text-[11px] text-faint">Looked up: {toolList(m.tools)}</p>}</div>)}
                  </div>
                </Card>
              ) : (
                <Empty title="The coach needs an Anthropic API key">
                  Set ANTHROPIC_API_KEY (and optionally ANTHROPIC_MODEL) in the server environment and restart. The key stays on the server; answers are generated by Claude from your own journal data.
                </Empty>
              )}
            </div>
          )}
        </div>
      </div>
    </>
  );
}
